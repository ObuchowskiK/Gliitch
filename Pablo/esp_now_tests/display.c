static void oled_send_command(uint8_t command) {
    i2c_cmd_handle_t cmd = i2c_cmd_link_create();
    i2c_master_start(cmd);
    i2c_master_write_byte(cmd, (OLED_I2C_ADDRESS << 1) | I2C_MASTER_WRITE, true);
    i2c_master_write_byte(cmd, 0x00, true);
    i2c_master_write_byte(cmd, command, true);
    i2c_master_stop(cmd);
    i2c_master_cmd_begin(I2C_MASTER_NUM, cmd, pdMS_TO_TICKS(10));
    i2c_cmd_link_delete(cmd);
}

static void oled_send_data(uint8_t *data, size_t length) {
    i2c_cmd_handle_t cmd = i2c_cmd_link_create();
    i2c_master_start(cmd);
    i2c_master_write_byte(cmd, (OLED_I2C_ADDRESS << 1) | I2C_MASTER_WRITE, true);
    i2c_master_write_byte(cmd, 0x40, true);
    i2c_master_write(cmd, data, length, true);
    i2c_master_stop(cmd);
    i2c_master_cmd_begin(I2C_MASTER_NUM, cmd, pdMS_TO_TICKS(50));
    i2c_cmd_link_delete(cmd);
}

void display_clear_buffer(void) {
    memset(frame_buffer, 0, sizeof(frame_buffer));
}

void display_draw_pixel(int x, int y, int color) {
    if (x < 0 || x >= OLED_WIDTH || y < 0 || y >= OLED_HEIGHT) return;
    uint16_t index = x + (y / 8) * OLED_WIDTH;
    uint8_t bit = y % 8;

    if (color) {
        frame_buffer[index] |= (1 << bit);  
    } else {
        frame_buffer[index] &= ~(1 << bit); 
    }
}

void display_draw_rect(int x, int y, int width, int height) {
    for (int i = x; i < x + width; i++) {
        for (int j = y; j < y + height; j++) {
            display_draw_pixel(i, j, 1);
        }
    }
}

// --- NEW TEXT RENDERING FUNCTIONS ---
static void display_draw_char(int x, int y, char c) {
    if (c < 32 || c > 127) return; // Ignore characters outside our ASCII array
    
    int font_idx = c - 32; // Offset by 32 (space) to match the array index
    
    // Each character is 5 columns wide
    for (int col = 0; col < 5; col++) {
        uint8_t line = font5x7[font_idx][col];
        
        // Each column is 8 pixels tall
        for (int row = 0; row < 8; row++) {
            if (line & (1 << row)) {
                display_draw_pixel(x + col, y + row, 1);
            }
        }
    }
}

void display_draw_text(int x, int y, const char *text) {
    int curr_x = x;
    while (*text) {
        display_draw_char(curr_x, y, *text);
        curr_x += 6; // Move 5 pixels for the character + 1 pixel for spacing
        text++;
    }
}
